// Shared types for the notes-to-quiz core loop.

export interface QuizQuestion {
  question: string;
  options: string[]; // always 4
  correctIndex: number; // 0-3
  explanation: string;
}

export interface Flashcard {
  front: string;
  back: string;
}

export interface GeneratedSet {
  questions: QuizQuestion[];
  flashcards: Flashcard[];
  source: "gemini" | "offline";
  note?: string;
}

// Mind map: a 3-level hierarchy (topic -> subtopics -> details).
// Depth is enforced by the generators: root is level 1, its children
// level 2, their children level 3 (leaves, children: []).
export interface MindMapNode {
  label: string;
  children: MindMapNode[];
}

export interface MindMapResult {
  root: MindMapNode;
  source: "gemini" | "offline";
  note?: string;
}

// Diagram: Mermaid source generated by Gemini for the process, cycle,
// or timeline described in the notes. No offline fallback exists for
// diagrams — a diagram without AI would be invented, not derived.
export type DiagramType = "flowchart" | "timeline";

export interface DiagramResult {
  mermaidCode: string;
  diagramType: DiagramType;
  title: string;
  source: "gemini";
}
